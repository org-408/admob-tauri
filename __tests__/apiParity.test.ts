// Every method and event of @capacitor-community/admob is here, under the same name, on every layer: the TypeScript
// API, the Tauri commands (Rust), the build script's command list (permissions), the default permission, the Swift
// plugin and the Kotlin plugin. The reference is the Capacitor package in node_modules (exact version in
// package.json), so a new or removed method or event upstream fails this test until it is ported.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

// @ts-expect-error plain JavaScript helper
import { interfaceMethods, snake } from '../scripts/api.mjs';

const root = join(__dirname, '..');
const read = (path: string) => readFileSync(join(root, path), 'utf8');
const files = (dir: string, ext: string) =>
  readdirSync(join(root, dir), { recursive: true })
    .map(String)
    .filter((f) => f.endsWith(ext))
    .sort()
    .map((f) => join(dir, f));
const readDir = (dir: string, ext: string) =>
  files(dir, ext)
    .map((f) => read(f))
    .join('\n');
const all = (source: string, pattern: RegExp) => [...source.matchAll(pattern)].map((m) => m[1]!);
const sorted = (names: string[]) => [...names].sort();

const upstream = 'node_modules/@capacitor-community/admob';
const crate = 'crates/admob-tauri';

/** The methods (not the listener ones) of every interface in upstream's .d.ts files */
const upstreamMethods = (): string[] => {
  const methods = new Set<string>();
  for (const file of files(`${upstream}/dist/esm`, '.d.ts')) {
    const source = read(file);
    for (const name of all(source, /export interface (\w+)(?: extends [^{]+)? \{/g)) {
      for (const method of interfaceMethods(source, name) as string[]) {
        if (method !== 'addListener' && method !== 'removeAllListeners') methods.add(method);
      }
    }
  }
  return [...methods];
};

/** The event names: every `= 'value'` of the enums in the .d.ts files / TypeScript sources */
const events = (dir: string, ext: string) =>
  sorted(all(readDir(dir, ext), /^\s+\w+ ?= ?["']([\w]+)["'],?$/gm).filter((e) => /^[a-z]/.test(e)));

const swiftMethods = (dir: string) => all(readDir(dir, '.swift'), /@objc public func (\w+)\(_ invoke: Invoke\)/g);
const kotlinMethods = (dir: string) => all(readDir(dir, '.kt'), /@Command\n\s+fun (\w+)\(invoke: Invoke\)/g);

/** Native methods of Tauri's own listener commands, not part of the Capacitor API */
const LISTENER_COMMANDS = ['register_listener', 'remove_listener'];

describe('admob-tauri has every method of @capacitor-community/admob', () => {
  const methods = upstreamMethods();
  const commands: string[] = methods.map(snake);

  it('reads the methods of @capacitor-community/admob 8.3.0', () => {
    expect(read(`${upstream}/package.json`)).toContain('"version": "8.3.0"');
    expect(methods).toContain('showBanner');
    expect(methods).toContain('requestConsentInfo');
    expect(methods).toHaveLength(29);
  });

  it('names a Tauri command for each method in the TypeScript API', async () => {
    const { COMMANDS } = await import('../crates/admob-tauri/guest-js/commands');
    expect(sorted(Object.keys(COMMANDS))).toEqual(sorted(methods));
    for (const [method, command] of Object.entries(COMMANDS)) {
      expect(command).toBe(snake(method));
    }
  });

  it('exposes each method on AdMob', async () => {
    const { AdMob } = await import('../crates/admob-tauri/guest-js/index');
    for (const method of methods.filter((m) => !/NativeAd(?!s)|NativeAdFeed/.test(m))) {
      expect(typeof (AdMob as unknown as Record<string, unknown>)[method], method).toBe('function');
    }
  });

  it('has a Rust command for each, calling the native method of the same name', () => {
    const rust = [...read(`${crate}/src/commands.rs`).matchAll(/^ {2}(\w+) => "(\w+)",$/gm)].map((m) => [m[1]!, m[2]!]);
    const ours = rust.filter(([c]) => !LISTENER_COMMANDS.includes(c!));
    expect(sorted(ours.map(([, m]) => m!))).toEqual(sorted(methods));
    for (const [command, method] of rust) expect(command).toBe(snake(method!));
    expect(rust.map(([c]) => c)).toHaveLength(methods.length + LISTENER_COMMANDS.length);
  });

  it('lists each command for the permissions, and allows every one by default', () => {
    const build = read(`${crate}/build.rs`);
    const listed = all(build.slice(build.indexOf('const COMMANDS')), /"(\w+)",/g);
    expect(sorted(listed)).toEqual(sorted([...commands, ...LISTENER_COMMANDS]));
    const allowed = all(read(`${crate}/permissions/default.toml`), /"allow-([\w-]+)"/g);
    expect(allowed).toEqual(listed.map((c) => c.replaceAll('_', '-')));
    for (const command of listed) {
      expect(existsSync(join(root, `${crate}/permissions/autogenerated/commands/${command}.toml`)), command).toBe(true);
    }
  });

  it('implements each in the Swift plugin, as @capacitor-community/admob does', () => {
    const ours = swiftMethods(`${crate}/ios/Sources`);
    const theirs = all(
      readDir(`${upstream}/ios/Sources`, '.swift'),
      /CAPPluginMethod\(name: "(\w+)", returnType: CAPPluginReturnPromise\)/g,
    );
    expect(sorted(ours)).toEqual(sorted(theirs));
    // upstream's Swift plugin has no snapshot methods: they are Android-only
    expect(sorted(theirs)).toEqual(sorted(methods.filter((m) => !/NativeAdSnapshot/.test(m))));
  });

  it('implements each in the Kotlin plugin, as @capacitor-community/admob does', () => {
    const ours = kotlinMethods(`${crate}/android/src/main`);
    const theirs = all(
      readDir(`${upstream}/android/src/main`, '.java'),
      /@PluginMethod\s+public void (\w+)\(final PluginCall call\)/g,
    );
    expect(sorted(ours)).toEqual(sorted(theirs));
    expect(sorted(theirs)).toEqual(sorted(methods));
  });
});

describe('admob-tauri has every event of @capacitor-community/admob', () => {
  it('keeps the event names of the TypeScript API', () => {
    const theirs = events(`${upstream}/dist/esm`, '.d.ts');
    expect(theirs.length).toBeGreaterThan(30);
    expect(events(`${crate}/guest-js`, '.ts')).toEqual(theirs);
  });

  it('notifies each event from the Swift and Kotlin plugins', () => {
    const theirs = events(`${upstream}/dist/esm`, '.d.ts');
    const swift = readDir(`${crate}/ios/Sources`, '.swift');
    const kotlin = readDir(`${crate}/android/src/main`, '.kt') + readDir(`${crate}/android/src/main`, '.java');
    for (const event of theirs) {
      // the iOS and Android plugins name an event by its enum case or by its string
      expect(swift + kotlin, event).toContain(event);
    }
  });
});

describe('versions', () => {
  it('are the same in Cargo.toml and the package.json files', () => {
    const cargo = /^version = "([^"]+)"/m.exec(read('Cargo.toml'))![1];
    expect(JSON.parse(read('package.json')).version).toBe(cargo);
    expect(JSON.parse(read(`${crate}/package.json`)).version).toBe(cargo);
  });
});
